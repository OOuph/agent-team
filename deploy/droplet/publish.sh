#!/usr/bin/env bash
# publish.sh — pull every pilot site repo listed in sites.tsv and publish its
# prebuilt public_dir atomically (symlink swap). Runs from agent-team-publish.timer
# every 5 minutes and from add-site.sh. Idempotent: an unchanged HEAD is skipped.
#
# Usage: publish.sh [--site <slug>] [--force] [--no-indexnow]
#   --site <slug>  process only this slug
#   --force        republish even if HEAD did not change
#   --no-indexnow  do not notify IndexNow after publishing
#
# After every publish (new sha, or --force) the release's URLs (sitemap.xml <loc>, max 10 000;
# only https://<host>/ when there is no sitemap) are POSTed to IndexNow with the shared key from
# /etc/agent-team/indexnow.key (keyLocation https://<host>/<key>.txt, served by nginx). A failed
# submission is a warning in the log, never a failed publish. INDEXNOW_ENDPOINT overrides the API.
# Exit codes: 0 all sites ok or skipped · 1 at least one site failed (clone/rsync/smoke).
# Journal: /var/log/agent-team/publish.log · state: /var/lib/agent-team/state/<slug>.json
set -euo pipefail
umask 022

# ---------------------------------------------------------------- settings
SITES_FILE="${SITES_FILE:-/etc/agent-team/sites.tsv}"
SITES_DIR="${SITES_DIR:-/opt/agent-team/sites}"          # git clones, one per slug
WWW_DIR="${WWW_DIR:-/var/www}"                           # /var/www/<slug> -> /var/www/<slug>-releases/<sha>
STATE_DIR="${STATE_DIR:-/var/lib/agent-team/state}"
LOG_FILE="${LOG_FILE:-/var/log/agent-team/publish.log}"
LOCK_FILE="${LOCK_FILE:-/run/lock/agent-team-publish.lock}"
LOCK_WAIT_SEC="${LOCK_WAIT_SEC:-300}"
KEEP_RELEASES="${KEEP_RELEASES:-5}"
CLONE_DEPTH="${CLONE_DEPTH:-50}"
SMOKE_TIMEOUT_SEC="${SMOKE_TIMEOUT_SEC:-15}"
SMOKE_RESOLVE_IP="${SMOKE_RESOLVE_IP:-127.0.0.1}"
INDEXNOW_ENDPOINT="${INDEXNOW_ENDPOINT:-https://api.indexnow.org/indexnow}"   # override for tests
INDEXNOW_KEY_FILE="${INDEXNOW_KEY_FILE:-/etc/agent-team/indexnow.key}"         # generated by install.sh
INDEXNOW_MAX_URLS="${INDEXNOW_MAX_URLS:-10000}"                                # protocol cap per request
INDEXNOW_TIMEOUT_SEC="${INDEXNOW_TIMEOUT_SEC:-20}"
INDEXNOW_SITEMAP="${INDEXNOW_SITEMAP:-sitemap.xml}"                            # relative to the release dir

FORCE=0
ONLY_SLUG=""
INDEXNOW=1

usage() {
  sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'
}

while [ $# -gt 0 ]; do
  case "$1" in
    --force) FORCE=1 ;;
    --no-indexnow) INDEXNOW=0 ;;
    --site)
      [ $# -ge 2 ] || { echo "ERROR: --site needs a slug" >&2; exit 64; }
      ONLY_SLUG="$2"; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "ERROR: unknown argument: $1" >&2; usage >&2; exit 64 ;;
  esac
  shift
done

now_iso() { date -u +%Y-%m-%dT%H:%M:%SZ; }

# log <message>: stdout (journal) + append to LOG_FILE
log() {
  local line
  line="$(now_iso) $*"
  echo "$line"
  echo "$line" >> "$LOG_FILE"
}

# write_state <slug> <host> <sha> <release> <smoke_status> <smoke_http_code> <published_at> <indexnow_code> <indexnow_urls>
write_state() {
  python3 - "$STATE_DIR/$1.json" "$@" <<'PY'
import json, os, sys
path, slug, host, sha, release, smoke, code, published_at, inow_code, inow_urls = sys.argv[1:11]
data = {
    "slug": slug,
    "host": host,
    "sha": sha,
    "release": release,
    "published_at": published_at,
    "smoke": smoke,            # ok | fail
    "smoke_http_code": code,   # "200", "000" when nothing answered
    "indexnow_http_code": inow_code,   # "200"/"202" ok · other HTTP code · "000" no answer · "skip" / "nokey" / "off"
    "indexnow_urls": int(inow_urls),
}
tmp = path + ".tmp"
with open(tmp, "w") as f:
    json.dump(data, f, indent=2)
    f.write("\n")
os.replace(tmp, path)
PY
}

# swap_symlink <target_dir> <link_path>: atomic replace of a symlink. rename(2) does
# not follow symlinks, so a reader sees either the old or the new release, never none.
swap_symlink() {
  local target="$1" link="$2" tmp
  tmp="$link.tmp.$$"
  ln -sfn "$target" "$tmp"
  python3 -c 'import os, sys; os.replace(sys.argv[1], sys.argv[2])' "$tmp" "$link"
}

# smoke <host> -> prints the HTTP code ("000" if nothing answered); never fails the script
smoke() {
  local host="$1" code
  code="$(curl -sS -o /dev/null -w '%{http_code}' --max-time "$SMOKE_TIMEOUT_SEC" \
            --resolve "$host:443:$SMOKE_RESOLVE_IP" "https://$host/" 2>/dev/null || true)"
  [ -n "$code" ] || code="000"
  echo "$code"
}

# indexnow_urls <host> <release_dir> -> prints one absolute URL per line (max INDEXNOW_MAX_URLS):
# every <loc> of <release>/sitemap.xml (XML entities &amp; &lt; &gt; &quot; &#39; unescaped),
# or just https://<host>/ when the sitemap is missing or has no <loc>.
indexnow_urls() {
  local host="$1" release="$2" sitemap="$2/$INDEXNOW_SITEMAP" urls
  urls=""
  if [ -f "$sitemap" ]; then
    urls="$(tr -d '\r\n' < "$sitemap" \
      | grep -o '<loc>[^<]*</loc>' \
      | sed -e 's|^<loc>||' -e 's|</loc>$||' \
            -e 's/&amp;/\&/g' -e 's/&lt;/</g' -e 's/&gt;/>/g' -e 's/&quot;/"/g' -e "s/&#39;/'/g" -e "s/&apos;/'/g" \
            -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' \
      | grep -E '^https?://' \
      | head -n "$INDEXNOW_MAX_URLS" || true)"
  fi
  if [ -n "$urls" ]; then
    printf '%s\n' "$urls"
  else
    printf 'https://%s/\n' "$host"
  fi
}

# indexnow_submit <slug> <host> <release_dir> -> prints "<http_code> <n_urls>" on stdout (captured by
# the caller); progress lines go to fd 4 (the script's real stdout, opened in main). Never fails the script.
# http_code: "200"/"202" accepted · other HTTP code = rejected · "000" no answer / curl error ·
# "nokey" key file missing · "off" (--no-indexnow). Body of a non-2xx answer goes to the journal.
indexnow_submit() {
  local slug="$1" host="$2" release="$3" key urlfile payload body code n
  if [ "$INDEXNOW" = 0 ]; then echo "off 0"; return 0; fi
  if [ ! -s "$INDEXNOW_KEY_FILE" ]; then
    echo "[$slug] indexnow: $INDEXNOW_KEY_FILE missing — not submitting (run install.sh)" >&2
    echo "nokey 0"; return 0
  fi
  key="$(tr -d '[:space:]' < "$INDEXNOW_KEY_FILE")"
  urlfile="$(mktemp)"; payload="$(mktemp)"; body="$(mktemp)"
  indexnow_urls "$host" "$release" > "$urlfile"
  n="$(grep -c . "$urlfile" || true)"
  # JSON is assembled by python3 so odd characters in URLs are escaped correctly
  if ! python3 - "$host" "$key" "$urlfile" "$payload" <<'PY'
import json, sys
host, key, urlfile, out = sys.argv[1:5]
urls = [l.strip() for l in open(urlfile, encoding="utf-8") if l.strip()]
doc = {"host": host, "key": key, "keyLocation": f"https://{host}/{key}.txt", "urlList": urls}
with open(out, "w", encoding="utf-8") as f:
    json.dump(doc, f, ensure_ascii=False)
PY
  then
    echo "[$slug] indexnow: could not build the payload" >&2
    rm -f "$urlfile" "$payload" "$body"
    echo "000 $n"; return 0
  fi
  echo "[$slug] indexnow: POST $INDEXNOW_ENDPOINT host=$host urls=$n keyLocation=https://$host/$key.txt" >&4
  code="$(curl -sS -o "$body" -w '%{http_code}' --max-time "$INDEXNOW_TIMEOUT_SEC" \
            -H 'Content-Type: application/json; charset=utf-8' \
            --data-binary "@$payload" "$INDEXNOW_ENDPOINT" 2>>"$body" || true)"
  [ -n "$code" ] || code="000"
  case "$code" in
    200|202) echo "[$slug] indexnow: HTTP $code — accepted ($n urls)" >&4 ;;
    *) echo "[$slug] WARNING: indexnow HTTP $code for $n urls: $(tr -d '\r\n' < "$body" | head -c 300)" >&2 ;;
  esac
  rm -f "$urlfile" "$payload" "$body"
  echo "$code $n"
}

# publish_site <slug> <host> <repo> <branch> <public_dir>
# Runs inside a subshell with set -e. Exit: 0 published · 10 skipped (same HEAD) ·
# 20 published but smoke failed · anything else = error.
publish_site() {
  local slug="$1" host="$2" repo="$3" branch="$4" public_dir="$5"
  local repo_dir="$SITES_DIR/$slug"
  local releases="$WWW_DIR/$slug-releases"
  local live="$WWW_DIR/$slug"
  local sha short release current src tmp code status ts old inow inow_code inow_n

  echo "[$slug] repo=$repo branch=$branch public_dir=$public_dir host=$host"

  if [ -e "$live" ] && [ ! -L "$live" ]; then
    echo "[$slug] ERROR: $live exists and is not a symlink; refusing to touch it" >&2
    exit 1
  fi

  # --- 1. clone or fetch --------------------------------------------------
  if [ ! -d "$repo_dir/.git" ]; then
    if [ -e "$repo_dir" ]; then
      echo "[$slug] removing incomplete checkout $repo_dir"
      rm -rf "$repo_dir"
    fi
    echo "[$slug] cloning (depth $CLONE_DEPTH) into $repo_dir"
    git clone --quiet --depth "$CLONE_DEPTH" --branch "$branch" "$repo" "$repo_dir"
  else
    echo "[$slug] fetching origin/$branch"
    git -C "$repo_dir" remote set-url origin "$repo"
    git -C "$repo_dir" fetch --quiet --depth "$CLONE_DEPTH" origin \
      "+refs/heads/$branch:refs/remotes/origin/$branch"
  fi
  git -C "$repo_dir" reset --quiet --hard "origin/$branch"

  sha="$(git -C "$repo_dir" rev-parse HEAD)"
  short="${sha:0:12}"
  release="$releases/$short"
  current=""
  [ -L "$live" ] && current="$(readlink "$live")"
  echo "[$slug] HEAD=$sha current=${current:-<none>}"

  # --- 2. skip when nothing changed ----------------------------------------
  if [ "$FORCE" = 0 ] && [ "$current" = "$release" ] && [ -d "$release" ]; then
    echo "[$slug] HEAD unchanged, release in place — skipping"
    log "slug=$slug sha=$short action=skipped"
    exit 10
  fi

  # --- 3. stage the release -------------------------------------------------
  src="$repo_dir/$public_dir"
  if [ ! -d "$src" ]; then
    echo "[$slug] ERROR: $src does not exist — is $public_dir committed in the repo?" >&2
    exit 1
  fi
  if [ ! -f "$src/index.html" ]; then
    echo "[$slug] WARNING: $src/index.html missing; publishing anyway" >&2
  fi
  mkdir -p "$releases"
  tmp="$releases/.$short.tmp"
  rm -rf "$tmp"
  echo "[$slug] rsync $src/ -> $tmp/"
  rsync -a --delete "$src/" "$tmp/"
  rm -rf "$release"
  mv "$tmp" "$release"
  chmod 755 "$release"

  # --- 4. atomic switch -----------------------------------------------------
  echo "[$slug] switching $live -> $release"
  swap_symlink "$release" "$live"
  ts="$(now_iso)"

  # --- 5. prune old releases (keep KEEP_RELEASES newest, never the live one) --
  while IFS= read -r old; do
    old="${old%/}"
    [ -n "$old" ] || continue
    [ "$old" = "$release" ] && continue
    echo "[$slug] pruning old release $old"
    rm -rf "$old"
  done < <(ls -1dt "$releases"/*/ 2>/dev/null | tail -n +$((KEEP_RELEASES + 1)) || true)

  # --- 6. smoke -------------------------------------------------------------
  code="$(smoke "$host")"
  if [ "$code" = "200" ]; then status="ok"; else status="fail"; fi
  echo "[$slug] smoke https://$host/ via $SMOKE_RESOLVE_IP -> HTTP $code ($status)"

  # --- 7. IndexNow (courtesy ping; never fails the publish) ----------------
  if [ "$status" = "ok" ]; then
    inow="$(indexnow_submit "$slug" "$host" "$release" || echo "000 0")"
  else
    echo "[$slug] indexnow: skipped — smoke failed, nothing worth announcing"
    inow="skip 0"
  fi
  inow_code="${inow%% *}"; inow_n="${inow##* }"

  write_state "$slug" "$host" "$sha" "$release" "$status" "$code" "$ts" "$inow_code" "$inow_n"
  log "slug=$slug sha=$short action=published release=$release smoke=$status http=$code"
  log "slug=$slug sha=$short action=indexnow indexnow=$inow_code urls=$inow_n host=$host"
  [ "$status" = "ok" ] || exit 20
}

# ---------------------------------------------------------------- main
exec 4>&1   # fd 4 = real stdout, for progress lines inside functions whose stdout is captured
echo "== agent-team publish $(now_iso) sites=$SITES_FILE force=$FORCE only=${ONLY_SLUG:-all} indexnow=$INDEXNOW"
mkdir -p "$SITES_DIR" "$WWW_DIR" "$STATE_DIR" "$(dirname "$LOG_FILE")" "$(dirname "$LOCK_FILE")"

if [ ! -f "$SITES_FILE" ]; then
  echo "no $SITES_FILE — nothing to publish (add sites with add-site.sh)"
  exit 0
fi

for bin in git rsync curl python3; do
  command -v "$bin" >/dev/null 2>&1 || { echo "ERROR: $bin not found" >&2; exit 1; }
done

# one publish at a time (timer vs. manual run / add-site.sh)
if command -v flock >/dev/null 2>&1; then
  exec 9>"$LOCK_FILE"
  if ! flock -w "$LOCK_WAIT_SEC" 9; then
    echo "ERROR: could not take $LOCK_FILE within ${LOCK_WAIT_SEC}s — another publish is running" >&2
    exit 1
  fi
fi

n_ok=0; n_skip=0; n_fail=0; n_smoke=0; failed_slugs=""
# sites.tsv is read on fd 3 so git/curl inside the loop cannot swallow lines from stdin
exec 3< "$SITES_FILE"
while IFS= read -r -u 3 line || [ -n "$line" ]; do
  line="${line%$'\r'}"
  case "$line" in ''|'#'*) continue ;; esac
  IFS=$'\t' read -r slug host repo branch public_dir _rest <<< "$line"
  branch="${branch:-main}"
  public_dir="${public_dir:-public}"
  if [ -n "$ONLY_SLUG" ] && [ "$slug" != "$ONLY_SLUG" ]; then
    continue
  fi
  if ! [[ "$slug" =~ ^[a-z0-9][a-z0-9-]*$ ]] || [ -z "$host" ] || [ -z "$repo" ]; then
    echo "ERROR: bad line in $SITES_FILE (need slug<TAB>host<TAB>repo[<TAB>branch[<TAB>public_dir]]): $line" >&2
    n_fail=$((n_fail + 1)); failed_slugs="$failed_slugs ${slug:-?}"
    continue
  fi

  set +e
  ( set -e; publish_site "$slug" "$host" "$repo" "$branch" "$public_dir" )
  rc=$?
  set -e
  case "$rc" in
    0)  n_ok=$((n_ok + 1)) ;;
    10) n_skip=$((n_skip + 1)) ;;
    20) n_smoke=$((n_smoke + 1)); failed_slugs="$failed_slugs $slug"
        echo "[$slug] published but smoke FAILED (see above)" >&2 ;;
    *)  n_fail=$((n_fail + 1)); failed_slugs="$failed_slugs $slug"
        log "slug=$slug action=error rc=$rc"
        echo "[$slug] ERROR: publish failed with rc=$rc" >&2 ;;
  esac
done
exec 3<&-

if [ -n "$ONLY_SLUG" ] && [ $((n_ok + n_skip + n_fail + n_smoke)) -eq 0 ]; then
  echo "ERROR: slug '$ONLY_SLUG' not found in $SITES_FILE" >&2
  exit 1
fi

echo "== done: published=$((n_ok + n_smoke)) skipped=$n_skip smoke_failed=$n_smoke errors=$n_fail${failed_slugs:+ (${failed_slugs# })}"
[ $((n_fail + n_smoke)) -eq 0 ]
